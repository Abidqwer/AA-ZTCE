"""TPM2-tools backend: TPM ECDSA audit signing and fresh quote verification.

Only public keys, wrapped child blobs and context files are written. Private key
material is generated by the TPM. A software TPM tests the protocol, not physical
key protection. Enrollment of the attestation key/reference PCRs is out-of-band.
"""
import base64
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile
import threading
from cryptography.hazmat.primitives import serialization,hashes
from cryptography.hazmat.primitives.asymmetric import ec


def canonical(v):return json.dumps(v,sort_keys=True,separators=(',',':'),allow_nan=False).encode()
def b64(v):return base64.b64encode(v).decode()
def unb64(v):return base64.b64decode(v,validate=True)


class TPMError(RuntimeError):pass


class TPM:
    algorithm='ECDSA-P256-SHA256'
    def __init__(self,tcti,audit_handle,attestation_handle,auth_file,public_file,*,tools_dir='',key_id='audit-tpm'):
        self.tcti=tcti;self.audit_handle=self.handle(audit_handle);self.attestation_handle=self.handle(attestation_handle)
        self.auth_file=str(Path(auth_file).resolve());self.tools_dir=tools_dir;self.key_id=key_id
        self._public=serialization.load_pem_public_key(Path(public_file).read_bytes())
        if not isinstance(self._public,ec.EllipticCurvePublicKey) or self._public.curve.name!='secp256r1':raise ValueError('TPM P-256 public key required')
        self.lock=threading.RLock()
        self._public.verify(self.sign(b'AA-ZTCE TPM startup'),b'AA-ZTCE TPM startup',ec.ECDSA(hashes.SHA256()))
    @staticmethod
    def handle(value):
        if not isinstance(value,str) or not re.fullmatch('0x81[0-7][0-9a-fA-F]{5}',value):raise ValueError('persistent owner handle required')
        return value
    def public_key(self):return self._public
    def run(self,tool,*args):
        env={**os.environ,'TPM2TOOLS_TCTI':self.tcti,'TPM2TOOLS_AUTOFLUSH':'yes'}
        executable=str(Path(self.tools_dir)/tool) if self.tools_dir else tool
        try:
            r=subprocess.run([executable,*map(str,args)],env=env,capture_output=True,timeout=10)
            if r.returncode:
                error=TPMError('TPM command failed: '+tool);error.diagnostic=r.stderr.decode(errors='replace')[:1500];raise error
            return r.stdout
        except (OSError,subprocess.TimeoutExpired):raise TPMError('TPM command unavailable: '+tool) from None
    def sign(self,message):
        if type(message) is not bytes or len(message)>1048576:raise ValueError('invalid TPM signing input')
        with self.lock,tempfile.TemporaryDirectory(prefix='aa-tpm-') as tmp:
            root=Path(tmp);(root/'data').write_bytes(message)
            self.run('tpm2_sign','-c',self.audit_handle,'-p','file:'+self.auth_file,'-g','sha256','-s','ecdsa','-f','plain','-o',root/'sig',root/'data')
            signature=(root/'sig').read_bytes()
            self._public.verify(signature,message,ec.ECDSA(hashes.SHA256()))
            return signature
    def quote(self,qualifying_hex,pcr_selection='sha256:0,7'):
        if not re.fullmatch('[a-f0-9]{64}',qualifying_hex):raise ValueError('32-byte qualifying digest required')
        if not re.fullmatch(r'sha256:(?:[0-9]|1[0-9]|2[0-3])(?:,(?:[0-9]|1[0-9]|2[0-3]))*',pcr_selection):raise ValueError('invalid PCR selection')
        with self.lock,tempfile.TemporaryDirectory(prefix='aa-quote-') as tmp:
            root=Path(tmp)
            self.run('tpm2_quote','-c',self.attestation_handle,'-p','file:'+self.auth_file,'-l',pcr_selection,
                '-q',qualifying_hex,'-g','sha256','-m',root/'quote','-s',root/'sig','-o',root/'pcrs','-f','plain')
            return {'quote':b64((root/'quote').read_bytes()),'signature':b64((root/'sig').read_bytes()),'pcrs':b64((root/'pcrs').read_bytes())}


def provision(tcti,directory,auth_file,*,parent_handle='0x8101a001',audit_handle='0x8101a002',attestation_handle='0x8101a003',tools_dir='',isolated_emulator=False,owner_auth_file=None):
    """Explicit enrollment. Refuses occupied handles; never clears a TPM."""
    root=Path(directory).resolve();root.mkdir(parents=True,exist_ok=False,mode=0o700)
    device=object.__new__(TPM);device.tcti=tcti;device.tools_dir=tools_dir
    handles=[TPM.handle(v) for v in (parent_handle,audit_handle,attestation_handle)]
    existing=device.run('tpm2_getcap','handles-persistent').decode()
    if any(h.lower() in existing.lower() for h in handles):raise ValueError('TPM handles occupied; enrollment refused')
    # TPM2-tools auto-flushes newly created/reloaded transient objects, not unrelated handles.
    owner_auth=['-P','file:'+str(Path(owner_auth_file).resolve())] if owner_auth_file else []
    device.run('tpm2_createprimary','-C','o',*owner_auth,'-G','ecc','-c',root/'parent.ctx')
    device.run('tpm2_evictcontrol','-C','o',*owner_auth,'-c',root/'parent.ctx',parent_handle)
    if isolated_emulator and not tcti.startswith('swtpm:'):raise ValueError('isolated emulator option requires swtpm')
    def cleanup_emulator_context(path):
        if isolated_emulator:device.run('tpm2_flushcontext','-t')
    cleanup_emulator_context(root/'parent.ctx')
    for name,handle,restricted in [('audit',audit_handle,False),('attestation',attestation_handle,True)]:
        attributes='fixedtpm|fixedparent|sensitivedataorigin|userwithauth|sign'+('|restricted' if restricted else '')
        device.run('tpm2_create','-C',parent_handle,'-G','ecc256:ecdsa-sha256:null','-a',attributes,
            '-p','file:'+str(Path(auth_file).resolve()),'-u',root/(name+'.pub'),'-r',root/(name+'.priv'))
        device.run('tpm2_load','-C',parent_handle,'-u',root/(name+'.pub'),'-r',root/(name+'.priv'),'-c',root/(name+'.ctx'))
        device.run('tpm2_evictcontrol','-C','o',*owner_auth,'-c',root/(name+'.ctx'),handle)
        cleanup_emulator_context(root/(name+'.ctx'))
        device.run('tpm2_readpublic','-c',handle,'-f','pem','-o',root/(name+'.pem'))
        cleanup_emulator_context(root/(name+'.ctx'))
    result={'tcti':tcti,'audit_handle':audit_handle,'attestation_handle':attestation_handle,
        'auth_file':str(Path(auth_file).resolve()),'public_file':str(root/'audit.pem'),'tools_dir':tools_dir,'key_id':'audit-tpm'}
    (root/'tpm-config.json').write_text(json.dumps(result,indent=2));return result


def verify_quote(evidence,qualifying_hex,public_pem,approved_pcr_sha256,*,tools_dir=''):
    if set(evidence)!={'quote','signature','pcrs'}:raise ValueError('invalid quote evidence')
    parts={k:unb64(v) for k,v in evidence.items()}
    if any(len(v)>65536 for v in parts.values()):raise ValueError('quote evidence too large')
    if hashlib.sha256(parts['pcrs']).hexdigest()!=approved_pcr_sha256:raise ValueError('PCR reference mismatch')
    with tempfile.TemporaryDirectory(prefix='aa-verifier-') as tmp:
        root=Path(tmp);(root/'public.pem').write_bytes(public_pem)
        for k,v in parts.items():(root/k).write_bytes(v)
        tool=str(Path(tools_dir)/'tpm2_checkquote') if tools_dir else 'tpm2_checkquote'
        r=subprocess.run([tool,'-u',str(root/'public.pem'),'-m',str(root/'quote'),'-s',str(root/'signature'),
            '-f',str(root/'pcrs'),'-g','sha256','-q',qualifying_hex],capture_output=True,timeout=10,
            env={**os.environ,'TPM2TOOLS_TCTI':'none'})
        if r.returncode:raise ValueError('quote signature, nonce or PCR digest invalid')
    return True
